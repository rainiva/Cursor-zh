'use strict';

const {
  createSurfaceTranslator,
  DEFAULT_DENY_SELECTORS,
  elementMatchesSelector,
  elementOrAncestorMatches,
  collectTextNodes,
  normalizeMatch,
  resolveTranslation,
} = require('./surface-translator.js');
const {
  createSurfaceRegistry,
  findSurfaceMatch,
  isConnected,
} = require('./surface-registry.js');

function buildSurfaceRegistryBootstrapLines() {
  return [
    '  function __cursorZhInstallSurfaceRegistry() {',
    '    function resolveWebCrypto(override) {',
    '      if (override && override.subtle) return override;',
    '      if (typeof globalThis !== "undefined" && globalThis.crypto && globalThis.crypto.subtle) {',
    '        return globalThis.crypto;',
    '      }',
    '      return null;',
    '    }',
    '    function isHmacAvailable(webCrypto) {',
    '      const cryptoApi = resolveWebCrypto(webCrypto);',
    '      return Boolean(cryptoApi && cryptoApi.subtle);',
    '    }',
    '    function createEphemeralKeyBytes(webCrypto) {',
    '      const cryptoApi = resolveWebCrypto(webCrypto);',
    '      if (!cryptoApi || typeof cryptoApi.getRandomValues !== "function") return null;',
    '      const bytes = new Uint8Array(32);',
    '      cryptoApi.getRandomValues(bytes);',
    '      return bytes;',
    '    }',
    '    function bytesToHex(buffer) {',
    '      const bytes = buffer instanceof Uint8Array ? buffer : new Uint8Array(buffer);',
    '      let hex = "";',
    '      for (let i = 0; i < bytes.length; i += 1) {',
    '        hex += bytes[i].toString(16).padStart(2, "0");',
    '      }',
    '      return hex;',
    '    }',
    '    async function hmacSha256Hex(keyBytes, value, webCrypto) {',
    '      const cryptoApi = resolveWebCrypto(webCrypto);',
    '      if (!cryptoApi || !cryptoApi.subtle || !keyBytes) {',
    '        throw new Error("Web Crypto unavailable");',
    '      }',
    '      const key = await cryptoApi.subtle.importKey(',
    '        "raw",',
    '        keyBytes,',
    '        { name: "HMAC", hash: "SHA-256" },',
    '        false,',
    '        ["sign"]',
    '      );',
    '      const encoded = new TextEncoder().encode(String(value));',
    '      const signature = await cryptoApi.subtle.sign("HMAC", key, encoded);',
    '      return bytesToHex(signature);',
    '    }',
    `    const DEFAULT_DENY_SELECTORS = ${JSON.stringify([...DEFAULT_DENY_SELECTORS])};`,
    `    const elementMatchesSelector = ${elementMatchesSelector.toString()};`,
    `    const elementOrAncestorMatches = ${elementOrAncestorMatches.toString()};`,
    `    const collectTextNodes = ${collectTextNodes.toString()};`,
    `    const normalizeMatch = ${normalizeMatch.toString()};`,
    `    const resolveTranslation = ${resolveTranslation.toString()};`,
    `    const createSurfaceTranslator = ${createSurfaceTranslator.toString()};`,
    `    const findSurfaceMatch = ${findSurfaceMatch.toString()};`,
    `    const isConnected = ${isConnected.toString()};`,
    `    const createSurfaceRegistry = ${createSurfaceRegistry.toString()};`,
    '    const shardsPayload = typeof runtimeSurfaceShards !== "undefined" && runtimeSurfaceShards',
    '      ? runtimeSurfaceShards',
    '      : { core: [], surfaces: {} };',
    '    const surfaces = shardsPayload.surfaces && typeof shardsPayload.surfaces === "object"',
    '      ? shardsPayload.surfaces',
    '      : {};',
    '    if (Object.keys(surfaces).length === 0) return null;',
    '    const registry = createSurfaceRegistry({',
    '      document: document,',
    '      shards: surfaces,',
    '      createTranslator: function createTranslator(opts) {',
    '        return createSurfaceTranslator(opts);',
    '      },',
    '    });',
    '    registry.installDiscoveryObserver();',
    '    try {',
    '      registry.discover(document.body || document.documentElement);',
    '    } catch (e) {}',
    '    return registry;',
    '  }',
    '  if (typeof globalThis !== "undefined") {',
    '    const surfaceRegistry = __cursorZhInstallSurfaceRegistry();',
    '    if (surfaceRegistry) {',
    '      globalThis.__cursorZhSurfaceRegistry = surfaceRegistry;',
    '    }',
    '  }',
  ];
}

module.exports = {
  buildSurfaceRegistryBootstrapLines,
};
